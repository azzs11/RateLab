//! Generates `results/RESULTS.md` and the README's results table from the JSON files.
//!
//! Nothing here measures anything: every number printed comes from a result file, and
//! each section names the machine and commit it was measured on.

use crate::cluster::ClusterResults;
use crate::local::{ACCURACY_KEYS, ACCURACY_LIMIT, Scenario, TENANTS};
use crate::machine::Machine;
use crate::results::{LocalResults, MemoryResults, StrategyResults};
use crate::stats::Summary;
use crate::strategies::{self, OUTAGE, SKEW_MS, StrategyRow};
use crate::svg;
use std::fmt::Write as _;

/// Marks the generated part of the README.
pub const README_START: &str = "<!-- results:start (generated by `just results`, do not edit) -->";
/// End of the generated part of the README.
pub const README_END: &str = "<!-- results:end -->";

/// Every result file the report can use. Missing files are skipped and listed.
#[derive(Debug, Default)]
pub struct Inputs {
    /// `local.json`.
    pub local: Option<LocalResults>,
    /// `memory.json`.
    pub memory: Option<MemoryResults>,
    /// `cluster.json`.
    pub cluster: Option<ClusterResults>,
    /// `strategies.json`.
    pub strategies: Option<StrategyResults>,
}

/// File name of the Pareto chart for a cluster size.
pub fn chart_name(nodes: usize) -> String {
    format!("pareto-{nodes}-nodes.svg")
}

/// The Pareto charts to write next to RESULTS.md: one per cluster size above 1.
pub fn charts(inputs: &Inputs) -> Vec<(String, String)> {
    let Some(st) = &inputs.strategies else {
        return Vec::new();
    };
    st.size
        .nodes
        .iter()
        .filter(|&&n| n > 1)
        .map(|&nodes| {
            let points: Vec<svg::Point> = st
                .matrix
                .iter()
                .filter(|r| r.nodes == nodes)
                .map(|r| svg::Point {
                    strategy: r.strategy.clone(),
                    scenario: r.scenario.clone(),
                    calls: r.calls_per_1k.mean,
                    error: r.error_pct.mean,
                })
                .collect();
            (
                chart_name(nodes),
                svg::pareto(
                    &points,
                    &format!(
                        "{nodes} nodes: store calls vs admission error, every traffic pattern"
                    ),
                ),
            )
        })
        .collect()
}

/// `mean (min–max)` with `d` decimals, or just the mean when there is no spread.
pub fn spread(s: &Summary, d: usize) -> String {
    let mean = format!("{:.*}", d, s.mean);
    let (min, max) = (format!("{:.*}", d, s.min), format!("{:.*}", d, s.max));
    if s.n <= 1 || min == max {
        mean
    } else {
        format!("{mean} ({min}–{max})")
    }
}

/// Decisions per second as millions, with spread.
fn per_sec(s: &Summary) -> String {
    let m = |v: f64| format!("{:.2}", v / 1e6);
    if s.n <= 1 {
        format!("{} M", m(s.mean))
    } else {
        format!("{} M ({}–{})", m(s.mean), m(s.min), m(s.max))
    }
}

fn machine_line(label: &str, m: &Machine) -> String {
    format!(
        "- **{label}:** {} · commit `{}` · {}\n",
        m.one_line(),
        m.git_commit,
        m.measured_at
    )
}

/// The full RESULTS.md.
pub fn results_md(inputs: &Inputs) -> String {
    let mut md = String::new();
    md.push_str("# Results\n\n");
    md.push_str(
        "Generated by `just results` from the JSON files in this folder. **Do not edit by hand**; \
         rerun the command instead. Values are `mean (min–max)` over the runs or seeds listed.\n\n",
    );

    md.push_str("## Machines\n\n");
    if let Some(l) = &inputs.local {
        md.push_str(&machine_line("In-process suite", &l.machine));
    }
    if let Some(m) = &inputs.memory {
        md.push_str(&machine_line("Memory", &m.machine));
    }
    if let Some(st) = &inputs.strategies {
        md.push_str(&machine_line("Strategy simulation", &st.machine));
    }
    if let Some(c) = &inputs.cluster {
        md.push_str(&machine_line("Cluster (inside the containers)", &c.machine));
        if let Some(host) = &c.host {
            let _ = writeln!(md, "- **Cluster host:** {host}");
        }
    }
    let missing: Vec<&str> = [
        ("local.json", inputs.local.is_none()),
        ("memory.json", inputs.memory.is_none()),
        ("cluster.json", inputs.cluster.is_none()),
        ("strategies.json", inputs.strategies.is_none()),
    ]
    .iter()
    .filter(|(_, missing)| *missing)
    .map(|(name, _)| *name)
    .collect();
    if !missing.is_empty() {
        let _ = writeln!(md, "- Not measured yet: {}", missing.join(", "));
    }
    md.push('\n');

    if let Some(l) = &inputs.local {
        local_sections(&mut md, l);
    }
    if let Some(m) = &inputs.memory {
        memory_section(&mut md, m);
    }
    if let Some(c) = &inputs.cluster {
        cluster_section(&mut md, c);
    }
    if let Some(st) = &inputs.strategies {
        strategies_section(&mut md, st);
    }

    md.push_str("## Reproduce\n\n```bash\njust results\n```\n\n");
    md.push_str(
        "See the README for what it runs. Numbers depend on the machine; compare runs on the same \
         machine only.\n",
    );
    md
}

fn local_sections(md: &mut String, l: &LocalResults) {
    let _ = write!(
        md,
        "## Accuracy against the exact oracle\n\n\
         The oracle admits a request exactly when the key stays within {ACCURACY_LIMIT} units in \
         every 1 s span. Each scenario has {ACCURACY_KEYS} keys and lasts {} s; seeded scenarios \
         run {} seeds. **Over** = allowed by the limiter but not by the oracle, **under** = the \
         reverse, both as % of requests. **Worst window** = the most units one key got in any \
         1 s span, as a multiple of the limit.\n\n",
        l.size.scenario_secs, l.size.seeds
    );
    for scenario in Scenario::ALL {
        let rows: Vec<_> = l
            .accuracy
            .iter()
            .filter(|r| r.scenario == scenario.name())
            .collect();
        if rows.is_empty() {
            continue;
        }
        let _ = writeln!(
            md,
            "### {} ({} requests per run)\n",
            scenario.name(),
            spread(&rows[0].requests, 0)
        );
        md.push_str(
            "| Algorithm | Over % | Under % | Admitted vs oracle % | Worst window × limit |\n",
        );
        md.push_str("|---|---:|---:|---:|---:|\n");
        for r in rows {
            let _ = writeln!(
                md,
                "| {} | {} | {} | {} | {} |",
                r.algorithm,
                spread(&r.over_pct, 2),
                spread(&r.under_pct, 2),
                spread(&r.admitted_vs_oracle_pct, 2),
                spread(&r.worst_window_ratio, 2)
            );
        }
        md.push('\n');
    }

    let _ = write!(
        md,
        "## Decision latency (in-process)\n\n\
         One thread, {} keys. Each sample times a batch of {} calls and divides by {}, because \
         one call can be shorter than the clock's resolution ({} ns on this machine; an empty \
         timed section reads as {} ns, median). {} samples per run, {} runs after a warm-up. Percentiles \
         are of these per-call averages, so single slow calls inside a batch are smoothed.\n\n\
         | Algorithm | p50 ns | p99 ns | p99.9 ns |\n|---|---:|---:|---:|\n",
        l.latency.first().map_or(0, |r| r.keys),
        l.latency.first().map_or(0, |r| r.batch),
        l.latency.first().map_or(0, |r| r.batch),
        l.timer.resolution_ns,
        l.timer.overhead_ns,
        l.size.latency_samples,
        l.size.runs
    );
    for r in &l.latency {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} |",
            r.algorithm,
            spread(&r.p50_ns, 1),
            spread(&r.p99_ns, 1),
            spread(&r.p999_ns, 1)
        );
    }
    md.push('\n');

    let _ = write!(
        md,
        "## Throughput (one shared limiter)\n\n\
         Decisions per second across all threads, keys picked uniformly at random, {} checks \
         per thread per run, {} runs after a warm-up.\n\n",
        l.size.checks_per_thread, l.size.runs
    );
    for &keys in &l.size.keys {
        let _ = writeln!(md, "### {keys} keys\n");
        md.push_str("| Algorithm |");
        for t in &l.size.threads {
            let _ = write!(md, " {t} threads |");
        }
        md.push_str("\n|---|");
        for _ in &l.size.threads {
            md.push_str("---:|");
        }
        md.push('\n');
        let algorithms: Vec<&str> = l.latency.iter().map(|r| r.algorithm.as_str()).collect();
        for a in algorithms {
            let _ = write!(md, "| {a} |");
            for &t in &l.size.threads {
                let cell = l
                    .throughput
                    .iter()
                    .find(|r| r.algorithm == a && r.threads == t && r.keys == keys)
                    .map_or_else(|| "–".to_owned(), |r| per_sec(&r.decisions_per_sec));
                let _ = write!(md, " {cell} |");
            }
            md.push('\n');
        }
        md.push('\n');
    }

    let _ = write!(
        md,
        "## Fairness between tenants\n\n\
         {TENANTS} tenants share 100 requests/s for {} s ({} seeds). Tenant 0 sends 200/s, the \
         others 20/s each, so every tenant wants more than an equal share. **global** = one \
         shared key with limit 100/s; **per_tenant** = one key per tenant with 10/s each. \
         Jain's index is 1 when every tenant gets the same.\n\n\
         | Algorithm | Keying | Jain's index | Noisy tenant's share % |\n|---|---|---:|---:|\n",
        l.size.scenario_secs, l.size.seeds
    );
    for r in &l.fairness {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} |",
            r.algorithm,
            r.keying,
            spread(&r.jain, 3),
            spread(&r.noisy_share_pct, 1)
        );
    }
    md.push('\n');
}

fn memory_section(md: &mut String, m: &MemoryResults) {
    let (keys, limit) = m.rows.first().map_or((0, 0), |r| (r.keys, r.limit));
    let _ = write!(
        md,
        "## Memory per key\n\n\
         Heap bytes per key with {keys} keys, counted by the allocator. **Full window** = after \
         {limit} requests per key (limit {limit}).\n\n\
         | Algorithm | After 1 request | Full window |\n|---|---:|---:|\n"
    );
    for r in &m.rows {
        let _ = writeln!(
            md,
            "| {} | {:.0} | {:.0} |",
            r.algorithm, r.bytes_per_key_one_request, r.bytes_per_key_full_window
        );
    }
    md.push('\n');
}

fn cluster_section(md: &mut String, c: &ClusterResults) {
    let _ = write!(
        md,
        "## {} nodes sharing one Redis (Docker Compose)\n\n\
         Each node runs the Axum server with the Redis token bucket. The load generator sends \
         open-loop Poisson traffic at {:.1}× the limit to {} keys (limit {} per {} s per key), \
         {} s per run, {} seeds, and records every request's send time. **vs one bucket** \
         compares with a single in-process token bucket fed the same send times: what a \
         perfectly coordinated cluster would decide. **vs oracle** compares with the exact \
         rule, as in the in-process tables. Redis counters come from Redis itself (`INFO`).\n\n",
        c.nodes, c.load_factor, c.keys, c.limit, c.window_secs, c.run_secs, c.seeds
    );
    md.push_str(
        "| Scenario | Node 0 share % | Sent/s | Over vs one bucket % | Under vs one bucket % | \
         Over vs oracle % | Worst window × limit |\n|---|---:|---:|---:|---:|---:|---:|\n",
    );
    for r in &c.scenarios {
        let _ = writeln!(
            md,
            "| {} | {:.0} | {} | {} | {} | {} | {} |",
            r.scenario,
            r.node0_share_pct,
            spread(&r.sent_per_sec, 0),
            spread(&r.over_vs_single_pct, 2),
            spread(&r.under_vs_single_pct, 2),
            spread(&r.over_vs_oracle_pct, 2),
            spread(&r.worst_window_ratio, 2)
        );
    }
    md.push_str(
        "\n| Scenario | Redis calls / 1k decisions | Redis commands / 1k | Redis bytes / decision | \
         p50 ms | p99 ms | p99.9 ms | No response % |\n|---|---:|---:|---:|---:|---:|---:|---:|\n",
    );
    for r in &c.scenarios {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            r.scenario,
            spread(&r.redis_calls_per_1k, 0),
            spread(&r.redis_commands_per_1k, 0),
            spread(&r.redis_bytes_per_decision, 0),
            spread(&r.p50_ms, 2),
            spread(&r.p99_ms, 2),
            spread(&r.p999_ms, 2),
            spread(&r.no_response_pct, 2)
        );
    }
    md.push_str(
        "\nLatency is measured at the load generator and includes Docker networking. Redis \
         commands include the 4 commands inside the Lua script (TIME, HMGET, HSET, PEXPIRE).\n\n",
    );
    if let Some(t) = &c.throughput {
        let _ = write!(
            md,
            "### Closed-loop throughput\n\n\
             {} requests in flight, spread over the nodes and about a million keys, {} s per run, \
             {} runs after a warm-up.\n\n\
             | Requests/s | p50 ms | p99 ms |\n|---:|---:|---:|\n| {} | {} | {} |\n\n",
            t.concurrency,
            t.secs,
            t.requests_per_sec.n,
            spread(&t.requests_per_sec, 0),
            spread(&t.p50_ms, 2),
            spread(&t.p99_ms, 2)
        );
    }
    if !c.resilience.is_empty() {
        let _ = write!(
            md,
            "### Redis outage\n\n\
             Redis stops running scripts from {:.0} s to {:.0} s (`CLIENT PAUSE ... WRITE`) while \
             traffic continues on both routes. `/api/hello` fails **open**, `/api/orders` fails \
             **closed**.{}{}\n\n\
             | Phase | Route (policy) | Requests | Allowed % | Over vs oracle % | Redis % | Breaker open % | Redis error % | No response % | p99 ms |\n\
             |---|---|---:|---:|---:|---:|---:|---:|---:|---:|\n",
            c.outage_secs.0,
            c.outage_secs.1,
            c.breaker.map_or_else(String::new, |b| format!(
                " Each node's breaker opens after {} consecutive failures and probes again after \
                 {} ms; Redis calls time out after {} ms.",
                b.failures, b.open_ms, b.redis_timeout_ms
            )),
            c.recovery_ms.map_or_else(
                || " Not every node had recovered by the end of the run.".to_owned(),
                |ms| format!(
                    " Every node was answering from Redis again {ms:.0} ms after Redis recovered."
                )
            )
        );
        for r in &c.resilience {
            let _ = writeln!(
                md,
                "| {} | {} ({}) | {} | {:.1} | {:.1} | {:.1} | {:.1} | {:.1} | {:.1} | {:.1} |",
                r.phase,
                r.route,
                r.failure_policy,
                r.requests,
                r.allowed_pct,
                r.over_vs_oracle_pct,
                r.redis_pct,
                r.breaker_open_pct,
                r.redis_error_pct,
                r.no_response_pct,
                r.p99_ms
            );
        }
        md.push('\n');
    }
}

/// Strategy names in report order.
const STRATEGY_ORDER: [&str; 5] = [
    "central_exact",
    "local_split",
    "async_sync",
    "fixed_leasing",
    "adaptive_leasing",
];

fn pivot(
    md: &mut String,
    rows: &[StrategyRow],
    nodes: usize,
    title: &str,
    cell: fn(&StrategyRow) -> String,
) {
    let _ = writeln!(md, "**{title}**\n");
    md.push_str("| Traffic |");
    for s in STRATEGY_ORDER {
        let _ = write!(md, " {s} |");
    }
    md.push_str("\n|---|");
    for _ in STRATEGY_ORDER {
        md.push_str("---:|");
    }
    md.push('\n');
    for scenario in strategies::traffic_names() {
        let _ = write!(md, "| {scenario} |");
        for s in STRATEGY_ORDER {
            let value = rows
                .iter()
                .find(|r| r.nodes == nodes && r.scenario == scenario && r.strategy == s)
                .map_or_else(|| "–".to_owned(), cell);
            let _ = write!(md, " {value} |");
        }
        md.push('\n');
    }
    md.push('\n');
}

fn strategies_section(md: &mut String, st: &StrategyResults) {
    let _ = write!(
        md,
        "## Coordination strategies (simulated cluster)\n\n\
         N nodes enforce one limit of {} per second per key together, through a shared store \
         (what Redis runs). Traffic is the in-process scenarios at the same load ({} keys), \
         plus **skewed**: steady Poisson with 80% of requests on node 0. Each configuration \
         runs {} s with {} seeds in the deterministic simulator (`crates/sim`): one-way delay \
         {} µs plus up to {} µs jitter, {} ms timeout. The network is simulated, so these \
         numbers describe the protocols, not a machine.\n\n\
         - **Admission error** = over + under, counted in units per key per 1 s window \
         against the **ideal**: one perfectly coordinated token bucket on the same arrival \
         times. Over = admitted above the ideal; under = missing below it; both as % of what \
         the ideal admitted.\n\
         - **Store calls** = messages from nodes to the store per 1,000 decisions.\n\
         - **Latency** = time a request waits for its decision (0 when decided locally).\n\n\
         Parameters: async sync every 10 ms; fixed leases of limit/4N tokens lasting one \
         window; adaptive leases start at limit/8N, double when used up within 100 ms, halve \
         when the store grants less than asked, and are returned after 200 ms idle.\n\n",
        st.limit,
        st.keys,
        st.size.secs,
        st.size.seeds,
        st.network.one_way_us,
        st.network.jitter_us,
        st.network.timeout_ms
    );
    for &nodes in &st.size.nodes {
        let _ = writeln!(
            md,
            "### {nodes} node{}\n",
            if nodes == 1 { "" } else { "s" }
        );
        if nodes > 1 {
            let _ = writeln!(
                md,
                "![Pareto chart for {nodes} nodes: store calls per 1,000 decisions against admission error]({})\n",
                chart_name(nodes)
            );
        }
        pivot(md, &st.matrix, nodes, "Admission error %", |r| {
            spread(&r.error_pct, 2)
        });
        pivot(
            md,
            &st.matrix,
            nodes,
            "Store calls per 1,000 decisions",
            |r| format!("{:.0}", r.calls_per_1k.mean),
        );
        pivot(md, &st.matrix, nodes, "Decision latency p99, µs", |r| {
            format!("{:.0}", r.p99_us.mean)
        });
    }

    let _ = write!(
        md,
        "### Clock skew\n\n\
         Steady traffic on 3 nodes whose clocks are offset by {:?} ms. \
         **central_exact_node_clock** lets each node send its own time to the store, as an \
         application-clock script does (it stores the caller's time as is); \
         **central_exact** uses the store's clock, like Redis `TIME`.\n\n\
         | Strategy | Error, no skew % | Error, skewed % | Over-admission, skewed % |\n\
         |---|---:|---:|---:|\n",
        SKEW_MS
    );
    for r in &st.skew {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} |",
            r.strategy,
            spread(&r.error_no_skew_pct, 2),
            spread(&r.error_skewed_pct, 2),
            spread(&r.over_skewed_pct, 2)
        );
    }

    let _ = write!(
        md,
        "\n### Store outage\n\n\
         Steady traffic on 3 nodes; the store is unreachable from {:.0}% to {:.0}% of the run. \
         Errors here are counted only for requests that arrived during the outage.\n\n\
         | Strategy | Policy | Allowed during % | Over during % | Under during % | Error, whole run % |\n\
         |---|---|---:|---:|---:|---:|\n",
        OUTAGE.0 * 100.0,
        OUTAGE.1 * 100.0
    );
    for r in &st.outage {
        let _ = writeln!(
            md,
            "| {} | fail {} | {:.1} | {:.1} | {:.1} | {} |",
            r.strategy,
            r.policy,
            r.during_allowed_pct.mean,
            r.during_over_pct.mean,
            r.during_under_pct.mean,
            spread(&r.overall_error_pct, 2)
        );
    }

    md.push_str(
        "\n### Traffic shift\n\n\
         Steady traffic on 3 nodes, all of it on node 0 for the first half and all on node 1 \
         for the second. **Rebalance** = time after the shift until three 100 ms bins in a row \
         admit at least 90% of what the ideal admits.\n\n\
         | Strategy | Under-admission, first second % | Rebalance ms | Runs that never rebalanced |\n\
         |---|---:|---:|---:|\n",
    );
    for r in &st.convergence {
        let rebalance = if r.rebalance_ms.n == 0 {
            "never".to_owned()
        } else {
            spread(&r.rebalance_ms, 0)
        };
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} |",
            r.strategy,
            spread(&r.under_first_second_pct, 1),
            rebalance,
            r.never
        );
    }

    md.push_str("\n### Where adaptive leasing loses\n\n");
    let beaten = strategies::dominated_by(&st.matrix, "adaptive_leasing");
    if beaten.is_empty() {
        md.push_str("No other strategy had both fewer store calls and less admission error in any configuration.\n\n");
    } else {
        md.push_str(
            "Configurations where another strategy had fewer (or equal) store calls **and** less \
             (or equal) admission error, one of them strictly:\n\n\
             | Traffic | Nodes | Better strategy | Its error % | Adaptive error % | Its calls/1k | Adaptive calls/1k |\n\
             |---|---:|---|---:|---:|---:|---:|\n",
        );
        for d in &beaten {
            let _ = writeln!(
                md,
                "| {} | {} | {} | {:.2} | {:.2} | {:.0} | {:.0} |",
                d.scenario, d.nodes, d.by, d.by_error, d.error, d.by_calls, d.calls
            );
        }
        md.push('\n');
    }
    let vs_fixed: Vec<&StrategyRow> = st
        .matrix
        .iter()
        .filter(|r| r.strategy == "adaptive_leasing" && r.nodes > 1)
        .collect();
    let fixed = |r: &StrategyRow| {
        st.matrix.iter().find(|f| {
            f.strategy == "fixed_leasing" && f.scenario == r.scenario && f.nodes == r.nodes
        })
    };
    let fewer_calls = vs_fixed
        .iter()
        .filter(|r| fixed(r).is_some_and(|f| r.calls_per_1k.mean < f.calls_per_1k.mean))
        .count();
    let less_error = vs_fixed
        .iter()
        .filter(|r| fixed(r).is_some_and(|f| r.error_pct.mean < f.error_pct.mean))
        .count();
    let _ = writeln!(
        md,
        "Against fixed leasing, over the {} multi-node configurations: adaptive leasing used \
         fewer store calls in {fewer_calls} and had less admission error in {less_error}.",
        vs_fixed.len()
    );
    let conv = |name: &str| st.convergence.iter().find(|r| r.strategy == name);
    if let (Some(a), Some(f)) = (conv("adaptive_leasing"), conv("fixed_leasing")) {
        let _ = writeln!(
            md,
            "After a traffic shift it took {} ms on average to rebalance, against {} ms for fixed \
             leasing.",
            spread(&a.rebalance_ms, 0),
            spread(&f.rebalance_ms, 0)
        );
    }
    md.push('\n');
}

/// The short table embedded in the README.
pub fn readme_block(inputs: &Inputs) -> String {
    let mut md = String::new();
    md.push_str(README_START);
    md.push('\n');
    let Some(l) = &inputs.local else {
        md.push_str("\nNo results yet: run `just results`.\n\n");
        md.push_str(README_END);
        return md;
    };
    let _ = write!(
        md,
        "\nMeasured on {} (commit `{}`, {}). Full tables, spreads and method: \
         [results/RESULTS.md](results/RESULTS.md).\n\n",
        l.machine.one_line(),
        l.machine.git_commit,
        l.machine.measured_at
    );
    let one_thread_keys = l
        .size
        .keys
        .iter()
        .copied()
        .find(|&k| k == 1_000)
        .unwrap_or(1);
    let _ = writeln!(
        md,
        "| Algorithm | Worst window, boundary attack (× limit) | Over-admission, steady Poisson % | p50 latency ns | 1 thread, {one_thread_keys} keys | Bytes/key, full window |"
    );
    md.push_str("|---|---:|---:|---:|---:|---:|\n");
    for lat in &l.latency {
        let a = lat.algorithm.as_str();
        let acc = |scenario: &str| {
            l.accuracy
                .iter()
                .find(|r| r.algorithm == a && r.scenario == scenario)
        };
        let attack =
            acc("boundary_attack").map_or("–".into(), |r| spread(&r.worst_window_ratio, 2));
        let over =
            acc("steady_poisson").map_or("–".into(), |r| format!("{:.2}", r.over_pct.mean));
        let tput = l
            .throughput
            .iter()
            .find(|r| r.algorithm == a && r.threads == 1 && r.keys == one_thread_keys)
            .map_or("–".into(), |r| {
                format!("{:.2} M/s", r.decisions_per_sec.mean / 1e6)
            });
        let mem = inputs
            .memory
            .as_ref()
            .and_then(|m| m.rows.iter().find(|r| r.algorithm == a))
            .map_or("–".into(), |r| {
                format!("{:.0}", r.bytes_per_key_full_window)
            });
        let _ = writeln!(
            md,
            "| {a} | {attack} | {over} | {:.1} | {tput} | {mem} |",
            lat.p50_ns.mean
        );
    }
    md.push('\n');
    if let Some(st) = &inputs.strategies
        && st.size.nodes.contains(&3)
    {
        let _ = write!(
            md,
            "**Coordination strategies**, 3 simulated nodes sharing one limit (every traffic \
             pattern, lower left is better):\n\n![Pareto chart: store calls against admission \
             error for 3 nodes](results/{})\n\n\
             | Strategy | Admission error, steady % | Admission error, skewed % | Store calls / 1k, steady | p99 wait µs, steady |\n\
             |---|---:|---:|---:|---:|\n",
            chart_name(3)
        );
        for name in STRATEGY_ORDER {
            let find = |scenario: &str| {
                st.matrix
                    .iter()
                    .find(|r| r.nodes == 3 && r.strategy == name && r.scenario == scenario)
            };
            if let (Some(steady), Some(skewed)) = (find("steady_poisson"), find("skewed")) {
                let _ = writeln!(
                    md,
                    "| {name} | {:.2} | {:.2} | {:.0} | {:.0} |",
                    steady.error_pct.mean,
                    skewed.error_pct.mean,
                    steady.calls_per_1k.mean,
                    steady.p99_us.mean
                );
            }
        }
        md.push('\n');
    }
    if let Some(c) = &inputs.cluster
        && let Some(uniform) = c.scenarios.iter().find(|r| r.scenario == "uniform")
    {
        let _ = writeln!(
            md,
            "**{} nodes sharing Redis** (Docker Compose on the same machine): over-admission \
             {:.2}% compared with one perfectly coordinated token bucket, {:.0} Redis calls per \
             1,000 decisions, p99 {:.2} ms at the client{}.\n",
            c.nodes,
            uniform.over_vs_single_pct.mean,
            uniform.redis_calls_per_1k.mean,
            uniform.p99_ms.mean,
            c.throughput.as_ref().map_or_else(String::new, |t| format!(
                ", {:.0} requests/s closed-loop",
                t.requests_per_sec.mean
            ))
        );
    }
    md.push_str(README_END);
    md
}

/// Replaces the text between the README markers. Errors if the markers are missing.
pub fn splice_readme(readme: &str, block: &str) -> anyhow::Result<String> {
    let start = readme
        .find(README_START)
        .ok_or_else(|| anyhow::anyhow!("README has no results start marker"))?;
    let end = readme[start..]
        .find(README_END)
        .map(|i| start + i + README_END.len())
        .ok_or_else(|| anyhow::anyhow!("README has no results end marker"))?;
    Ok(format!("{}{block}{}", &readme[..start], &readme[end..]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spread_hides_zero_spread() {
        let s = Summary::of(&[2.0, 2.0]);
        assert_eq!(spread(&s, 1), "2.0");
        let s = Summary::of(&[1.0, 3.0]);
        assert_eq!(spread(&s, 0), "2 (1–3)");
    }

    #[test]
    fn splice_replaces_only_the_block() {
        let readme = format!("intro\n{README_START}\nold\n{README_END}\noutro\n");
        let out = splice_readme(&readme, &format!("{README_START}\nnew\n{README_END}")).unwrap();
        assert_eq!(
            out,
            format!("intro\n{README_START}\nnew\n{README_END}\noutro\n")
        );
        assert!(splice_readme("no markers", "x").is_err());
    }

    #[test]
    fn empty_inputs_say_nothing_was_measured() {
        let md = results_md(&Inputs::default());
        assert!(
            md.contains("Not measured yet: local.json, memory.json, cluster.json, strategies.json")
        );
        assert!(readme_block(&Inputs::default()).contains("No results yet"));
    }
}
