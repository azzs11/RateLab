pub const README_END: &str = "<!-- results:end -->";

/// Every result file the report can use. Missing files are skipped and listed.
#[derive(Debug, Default)]
pub struct Inputs {
    /// `local.json`.
    pub local: Option<LocalResults>,
    /// `memory.json`.
    pub memory: Option<MemoryResults>,
    /// `cluster.json`.
    pub cluster: Option<ClusterResults>,
    /// `strategies.json`.
    pub strategies: Option<StrategyResults>,
    /// `traces.json`.
    pub traces: Option<TraceResults>,
    /// `real_strategies.json`.
    pub real_strategies: Option<RealStrategyResults>,
    /// `overload.json`.
    pub overload: Option<OverloadResults>,
    /// `llm.json`.
    pub llm: Option<LlmResults>,
}

/// The largest gaps between the real cluster and the simulator: admission error in
/// percentage points, store calls as a % of the real value.
pub fn sim_gap(r: &RealStrategyResults) -> (f64, f64) {
    let error = r
        .rows
        .iter()
        .map(|x| (x.real_error_pct.mean - x.sim_error_pct.mean).abs())
        .fold(0.0, f64::max);
    let calls = r
        .rows
        .iter()
        .filter(|x| x.real_calls_per_1k.mean > 0.0)
        .map(|x| {
            (x.real_calls_per_1k.mean - x.sim_calls_per_1k.mean).abs() * 100.0
                / x.real_calls_per_1k.mean
        })
        .fold(0.0, f64::max);
    (error, calls)
}

/// File name of the Pareto chart for a cluster size.
pub fn chart_name(nodes: usize) -> String {
    format!("pareto-{nodes}-nodes.svg")
}

/// The Pareto charts to write next to RESULTS.md: one per cluster size above 1.
pub fn charts(inputs: &Inputs) -> Vec<(String, String)> {
    let mut out = pareto_charts(inputs);
    if let Some(o) = &inputs.overload {
        out.extend(overload_charts(o));
    }
    if let Some(l) = &inputs.llm {
        out.extend(llm_chart(l));
    }
    out
}

/// File name of the LLM balance chart.
pub const LLM_CHART: &str = "llm-balance.svg";

const ACCOUNTING_STYLES: [(&str, &str, &str, f64); 3] = [
    ("estimate_only", "#E69F00", "9 3 2 3", 2.0),
    ("reserve_max", "#0072B2", "5 3", 2.0),
    ("admit_then_reconcile", "#009E73", "", 2.5),
];

/// The busiest tenant's output balance over time under each accounting mode.
fn llm_chart(l: &LlmResults) -> Option<(String, String)> {
    let sc = l.scenarios.iter().find(|s| s.name == "azure_2023")?;
    let mut series = vec![svg::Series {
        name: "zero (below: in debt)".into(),
        colour: "#1a1a1a",
        dash: "1 2",
        width: 1.0,
        points: vec![
            (0.0, 0.0),
            (
                sc.balance
                    .iter()
                    .flat_map(|b| b.1.last())
                    .map(|p| p.0)
                    .fold(0.0, f64::max),
                0.0,
            ),
        ],
    }];
    for (name, colour, dash, width) in ACCOUNTING_STYLES {
        if let Some((_, pts)) = sc.balance.iter().find(|(a, _)| a == name) {
            series.push(svg::Series {
                name: name.replace('_', " "),
                colour,
                dash,
                width,
                points: pts.iter().map(|&(t, b)| (t, b as f64)).collect(),
            });
        }
    }
    Some((
        LLM_CHART.to_owned(),
        svg::lines(
            &series,
            "Busiest tenant: output budget left over the first ten minutes (Azure trace, seed 1)",
            "Seconds",
            "Output units left",
        ),
    ))
}

/// File name of the overload chart for a scenario.
pub fn overload_chart_name(scenario: &str) -> String {
    format!("overload-{scenario}.svg")
}

/// Colour, dash pattern and width per limiter (Okabe–Ito colours).
const LIMITER_STYLES: [(&str, &str, &str, f64); 4] = [
    ("none", "#E69F00", "9 3 2 3", 2.0),
    ("static", "#0072B2", "", 2.0),
    ("aimd", "#CC79A7", "5 3", 2.0),
    ("gradient2", "#009E73", "", 3.0),
];

/// Goodput over time per scenario, from the real runs (or the simulated ones).
fn overload_charts(o: &OverloadResults) -> Vec<(String, String)> {
    o.scenarios
        .iter()
        .map(|sc| {
            let source = if sc.series.iter().any(|l| l.source == "real") {
                "real"
            } else {
                "simulated"
            };
            let lines: Vec<_> = sc.series.iter().filter(|l| l.source == source).collect();
            let mut series = Vec::new();
            if let Some(first) = lines.first() {
                series.push(svg::Series {
                    name: "offered".into(),
                    colour: "#999999",
                    dash: "2 3",
                    width: 1.5,
                    points: first.points.iter().map(|p| (p.t, p.offered_rps)).collect(),
                });
                series.push(svg::Series {
                    name: "best possible".into(),
                    colour: "#1a1a1a",
                    dash: "1 2",
                    width: 2.0,
                    points: first.points.iter().map(|p| (p.t, p.possible_rps)).collect(),
                });
            }
            for (name, colour, dash, width) in LIMITER_STYLES {
                if let Some(l) = lines.iter().find(|l| l.limiter == name) {
                    series.push(svg::Series {
                        name: format!("{name} (200s)"),
                        colour,
                        dash,
                        width,
                        points: l.points.iter().map(|p| (p.t, p.ok_rps)).collect(),
                    });
                }
            }
            (
                overload_chart_name(&sc.name),
                svg::lines(
                    &series,
                    &format!(
                        "{}: successful answers per second ({source}, seed 1)",
                        sc.name
                    ),
                    "Seconds",
                    "Requests per second",
                ),
            )
        })
        .collect()
}

fn pareto_charts(inputs: &Inputs) -> Vec<(String, String)> {
    let Some(st) = &inputs.strategies else {
        return Vec::new();
    };
    st.size
        .nodes
        .iter()
        .filter(|&&n| n > 1)
        .map(|&nodes| {
            let points: Vec<svg::Point> = st
                .matrix
                .iter()
                .filter(|r| r.nodes == nodes)
                .map(|r| svg::Point {
                    strategy: r.strategy.clone(),
                    scenario: r.scenario.clone(),
                    calls: r.calls_per_1k.mean,
                    error: r.error_pct.mean,
                })
                .collect();
            (
                chart_name(nodes),
                svg::pareto(
                    &points,
                    &format!(
                        "{nodes} nodes: store calls vs admission error, every traffic pattern"
                    ),
                ),
            )
        })
        .collect()
}

/// `mean (min–max)` with `d` decimals, or just the mean when there is no spread.
pub fn spread(s: &Summary, d: usize) -> String {
    let mean = format!("{:.*}", d, s.mean);
    let (min, max) = (format!("{:.*}", d, s.min), format!("{:.*}", d, s.max));
    if s.n <= 1 || min == max {
        mean
    } else {
        format!("{mean} ({min}–{max})")
    }
}

/// Decisions per second as millions, with spread.
fn per_sec(s: &Summary) -> String {
    let m = |v: f64| format!("{:.2}", v / 1e6);
    if s.n <= 1 {
        format!("{} M", m(s.mean))
    } else {
        format!("{} M ({}–{})", m(s.mean), m(s.min), m(s.max))
    }
}

fn machine_line(label: &str, m: &Machine) -> String {
    format!(
        "- **{label}:** {} · commit `{}` · {}\n",
        m.one_line(),
        m.git_commit,
        m.measured_at
    )
}

/// The full RESULTS.md.
pub fn results_md(inputs: &Inputs) -> String {
    let mut md = String::new();
    md.push_str("# Results\n\n");
    md.push_str(
        "Generated by `just results` from the JSON files in this folder. **Do not edit by hand**; \
         rerun the command instead. Values are `mean (min–max)` over the runs or seeds listed.\n\n",
    );

    md.push_str("## Machines\n\n");
    if let Some(l) = &inputs.local {
        md.push_str(&machine_line("In-process suite", &l.machine));
    }
    if let Some(m) = &inputs.memory {
        md.push_str(&machine_line("Memory", &m.machine));
    }
    if let Some(st) = &inputs.strategies {
        md.push_str(&machine_line("Strategy simulation", &st.machine));
    }
    if let Some(t) = &inputs.traces {
        md.push_str(&machine_line("Real traffic replay", &t.machine));
    }
    if let Some(r) = &inputs.real_strategies {
        md.push_str(&machine_line(
            "Strategies on the real cluster (inside the containers)",
            &r.machine,
        ));
    }
    if let Some(o) = &inputs.overload {
        md.push_str(&machine_line("Overload", &o.machine));
    }
    if let Some(l) = &inputs.llm {
        md.push_str(&machine_line("LLM tokens", &l.machine));
    }
    if let Some(c) = &inputs.cluster {
        md.push_str(&machine_line("Cluster (inside the containers)", &c.machine));
        if let Some(host) = &c.host {
            let _ = writeln!(md, "- **Cluster host:** {host}");
        }
    }
    let missing: Vec<&str> = [
        ("local.json", inputs.local.is_none()),
        ("memory.json", inputs.memory.is_none()),
        ("cluster.json", inputs.cluster.is_none()),
        ("strategies.json", inputs.strategies.is_none()),
        ("traces.json", inputs.traces.is_none()),
        ("real_strategies.json", inputs.real_strategies.is_none()),
        ("overload.json", inputs.overload.is_none()),
        ("llm.json", inputs.llm.is_none()),
    ]
    .iter()
    .filter(|(_, missing)| *missing)
    .map(|(name, _)| *name)
    .collect();
    if !missing.is_empty() {
        let _ = writeln!(md, "- Not measured yet: {}", missing.join(", "));
    }
    md.push('\n');

    if let Some(l) = &inputs.local {
        local_sections(&mut md, l);
    }
    if let Some(m) = &inputs.memory {
        memory_section(&mut md, m);
    }
    if let Some(c) = &inputs.cluster {
        cluster_section(&mut md, c);
    }
    if let Some(st) = &inputs.strategies {
        strategies_section(&mut md, st);
    }
    if let Some(r) = &inputs.real_strategies {
        real_strategies_section(&mut md, r);
    }
    if let Some(t) = &inputs.traces {
        traces_section(&mut md, t);
    }
    if let Some(o) = &inputs.overload {
        overload_section(&mut md, o);
    }
    if let Some(l) = &inputs.llm {
        llm_section(&mut md, l);
    }

    md.push_str("## Reproduce\n\n```bash\njust results\n```\n\n");
    md.push_str(
        "See the README for what it runs. Numbers depend on the machine; compare runs on the same \
         machine only.\n",
    );
    md
}

fn local_sections(md: &mut String, l: &LocalResults) {
    let _ = write!(
        md,
        "## Accuracy against the exact oracle\n\n\
         The oracle admits a request exactly when the key stays within {ACCURACY_LIMIT} units in \
         every 1 s span. Each scenario has {ACCURACY_KEYS} keys and lasts {} s; seeded scenarios \
         run {} seeds. **Over** = allowed by the limiter but not by the oracle, **under** = the \
         reverse, both as % of requests. **Worst window** = the most units one key got in any \
         1 s span, as a multiple of the limit.\n\n",
        l.size.scenario_secs, l.size.seeds
    );
    for scenario in Scenario::ALL {
        let rows: Vec<_> = l
            .accuracy
            .iter()
            .filter(|r| r.scenario == scenario.name())
            .collect();
        if rows.is_empty() {
            continue;
        }
        let _ = writeln!(
            md,
            "### {} ({} requests per run)\n",
            scenario.name(),
            spread(&rows[0].requests, 0)
        );
        md.push_str(
            "| Algorithm | Over % | Under % | Admitted vs oracle % | Worst window × limit |\n",
        );
        md.push_str("|---|---:|---:|---:|---:|\n");
        for r in rows {
            let _ = writeln!(
                md,
                "| {} | {} | {} | {} | {} |",
                r.algorithm,
                spread(&r.over_pct, 2),
                spread(&r.under_pct, 2),
                spread(&r.admitted_vs_oracle_pct, 2),
                spread(&r.worst_window_ratio, 2)
            );
        }
        md.push('\n');
    }

    let _ = write!(
        md,
        "## Decision latency (in-process)\n\n\
         One thread, {} keys. Each sample times a batch of {} calls and divides by {}, because \
         one call can be shorter than the clock's resolution ({} ns on this machine; an empty \
         timed section reads as {} ns, median). {} samples per run, {} runs after a warm-up. Percentiles \
         are of these per-call averages, so single slow calls inside a batch are smoothed.\n\n\
         | Algorithm | p50 ns | p99 ns | p99.9 ns |\n|---|---:|---:|---:|\n",
        l.latency.first().map_or(0, |r| r.keys),
        l.latency.first().map_or(0, |r| r.batch),
        l.latency.first().map_or(0, |r| r.batch),
        l.timer.resolution_ns,
        l.timer.overhead_ns,
        l.size.latency_samples,
        l.size.runs
    );
    for r in &l.latency {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} |",
            r.algorithm,
            spread(&r.p50_ns, 1),
            spread(&r.p99_ns, 1),
            spread(&r.p999_ns, 1)
        );
    }
    md.push('\n');

    let _ = write!(
        md,
        "## Throughput (one shared limiter)\n\n\
         Decisions per second across all threads, keys picked uniformly at random, {} checks \
         per thread per run, {} runs after a warm-up.\n\n",
        l.size.checks_per_thread, l.size.runs
    );
    for &keys in &l.size.keys {
        let _ = writeln!(md, "### {keys} keys\n");
        md.push_str("| Algorithm |");
        for t in &l.size.threads {
            let _ = write!(md, " {t} threads |");
        }
        md.push_str("\n|---|");
        for _ in &l.size.threads {
            md.push_str("---:|");
        }
        md.push('\n');
        let algorithms: Vec<&str> = l.latency.iter().map(|r| r.algorithm.as_str()).collect();
        for a in algorithms {
            let _ = write!(md, "| {a} |");
            for &t in &l.size.threads {
                let cell = l
                    .throughput
                    .iter()
                    .find(|r| r.algorithm == a && r.threads == t && r.keys == keys)
                    .map_or_else(|| "–".to_owned(), |r| per_sec(&r.decisions_per_sec));
                let _ = write!(md, " {cell} |");
            }
            md.push('\n');
        }
        md.push('\n');
    }

    let _ = write!(
        md,
        "## Fairness between tenants\n\n\
         {TENANTS} tenants share 100 requests/s for {} s ({} seeds). Tenant 0 sends 200/s, the \
         others 20/s each, so every tenant wants more than an equal share. **global** = one \
         shared key with limit 100/s; **per_tenant** = one key per tenant with 10/s each. \
         Jain's index is 1 when every tenant gets the same.\n\n\
         | Algorithm | Keying | Jain's index | Noisy tenant's share % |\n|---|---|---:|---:|\n",
        l.size.scenario_secs, l.size.seeds
    );
    for r in &l.fairness {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} |",
            r.algorithm,
            r.keying,
            spread(&r.jain, 3),
            spread(&r.noisy_share_pct, 1)
        );
    }
    md.push('\n');
}

fn memory_section(md: &mut String, m: &MemoryResults) {
    let (keys, limit) = m.rows.first().map_or((0, 0), |r| (r.keys, r.limit));
    let _ = write!(
        md,
        "## Memory per key\n\n\
         Heap bytes per key with {keys} keys, counted by the allocator. **Full window** = after \
         {limit} requests per key (limit {limit}).\n\n\
         | Algorithm | After 1 request | Full window |\n|---|---:|---:|\n"
    );
    for r in &m.rows {
        let _ = writeln!(
            md,
            "| {} | {:.0} | {:.0} |",
            r.algorithm, r.bytes_per_key_one_request, r.bytes_per_key_full_window
        );
    }
    md.push('\n');
}

fn cluster_section(md: &mut String, c: &ClusterResults) {
    let _ = write!(
        md,
        "## {} nodes sharing one Redis (Docker Compose)\n\n\
         Each node runs the Axum server with the Redis token bucket. The load generator sends \
         open-loop Poisson traffic at {:.1}× the limit to {} keys (limit {} per {} s per key), \
         {} s per run, {} seeds, and records every request's send time. **vs one bucket** \
         compares with a single in-process token bucket fed the same send times: what a \
         perfectly coordinated cluster would decide. **vs oracle** compares with the exact \
         rule, as in the in-process tables. Redis counters come from Redis itself (`INFO`).\n\n",
        c.nodes, c.load_factor, c.keys, c.limit, c.window_secs, c.run_secs, c.seeds
    );
    md.push_str(
        "| Scenario | Node 0 share % | Sent/s | Over vs one bucket % | Under vs one bucket % | \
         Over vs oracle % | Worst window × limit |\n|---|---:|---:|---:|---:|---:|---:|\n",
    );
    for r in &c.scenarios {
        let _ = writeln!(
            md,
            "| {} | {:.0} | {} | {} | {} | {} | {} |",
            r.scenario,
            r.node0_share_pct,
            spread(&r.sent_per_sec, 0),
            spread(&r.over_vs_single_pct, 2),
            spread(&r.under_vs_single_pct, 2),
            spread(&r.over_vs_oracle_pct, 2),
            spread(&r.worst_window_ratio, 2)
        );
    }
    md.push_str(
        "\n| Scenario | Redis calls / 1k decisions | Redis commands / 1k | Redis bytes / decision | \
         p50 ms | p99 ms | p99.9 ms | No response % |\n|---|---:|---:|---:|---:|---:|---:|---:|\n",
    );
    for r in &c.scenarios {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            r.scenario,
            spread(&r.redis_calls_per_1k, 0),
            spread(&r.redis_commands_per_1k, 0),
            spread(&r.redis_bytes_per_decision, 0),
            spread(&r.p50_ms, 2),
            spread(&r.p99_ms, 2),
            spread(&r.p999_ms, 2),
            spread(&r.no_response_pct, 2)
        );
    }
    md.push_str(
        "\nLatency is measured at the load generator and includes Docker networking. Redis \
         commands include the 4 commands inside the Lua script (TIME, HMGET, HSET, PEXPIRE).\n\n",
    );
    if let Some(t) = &c.throughput {
        let _ = write!(
            md,
            "### Closed-loop throughput\n\n\
             {} requests in flight, spread over the nodes and about a million keys, {} s per run, \
             {} runs after a warm-up.\n\n\
             | Requests/s | p50 ms | p99 ms |\n|---:|---:|---:|\n| {} | {} | {} |\n\n",
            t.concurrency,
            t.secs,
            t.requests_per_sec.n,
            spread(&t.requests_per_sec, 0),
            spread(&t.p50_ms, 2),
            spread(&t.p99_ms, 2)
        );
    }
    if !c.resilience.is_empty() {
        let _ = write!(
            md,
            "### Redis outage\n\n\
             Redis stops running scripts from {:.0} s to {:.0} s (`CLIENT PAUSE ... WRITE`) while \
             traffic continues on both routes. `/api/hello` fails **open**, `/api/orders` fails \
             **closed**.{}{}\n\n\
             | Phase | Route (policy) | Requests | Allowed % | Over vs oracle % | Redis % | Breaker open % | Redis error % | No response % | p99 ms |\n\
             |---|---|---:|---:|---:|---:|---:|---:|---:|---:|\n",
            c.outage_secs.0,
            c.outage_secs.1,
            c.breaker.map_or_else(String::new, |b| format!(
                " Each node's breaker opens after {} consecutive failures and probes again after \
                 {} ms; Redis calls time out after {} ms.",
                b.failures, b.open_ms, b.redis_timeout_ms
            )),
            c.recovery_ms.map_or_else(
                || " Not every node had recovered by the end of the run.".to_owned(),
                |ms| format!(
                    " Every node was answering from Redis again {ms:.0} ms after Redis recovered."
                )
            )
        );
        for r in &c.resilience {
            let _ = writeln!(
                md,
                "| {} | {} ({}) | {} | {:.1} | {:.1} | {:.1} | {:.1} | {:.1} | {:.1} | {:.1} |",
                r.phase,
                r.route,
                r.failure_policy,
                r.requests,
                r.allowed_pct,
                r.over_vs_oracle_pct,
                r.redis_pct,
                r.breaker_open_pct,
                r.redis_error_pct,
                r.no_response_pct,
                r.p99_ms
            );
        }
        md.push('\n');
    }
}

fn real_strategies_section(md: &mut String, r: &RealStrategyResults) {
    let (err_gap, calls_gap) = sim_gap(r);
    let _ = write!(
        md,
        "## Strategies on the real cluster, against the simulator\n\n\
         The {} Axum nodes run each coordination strategy for real, with Redis as the shared \
         store (the same Lua protocol the simulator models). The load generator sends {} keys \
         at {:.1}× the limit of {} per {} s, {} s per run, {} seeds, and records every request. \
         The **same recorded requests** (same send times, same nodes) are then replayed through \
         the simulator. Both sides are measured with the same code against one perfectly \
         coordinated token bucket.{}\n\n\
         Largest gap between real and simulated: **{:.2} percentage points** of admission error \
         and **{:.1}%** in store calls.\n\n\
         | Strategy | Traffic | Error real % | Error sim % | Calls/1k real | Calls/1k sim | p99 real µs | p99 sim µs |\n\
         |---|---|---:|---:|---:|---:|---:|---:|\n",
        r.nodes,
        r.keys,
        r.load_factor,
        r.limit,
        r.window_secs,
        r.run_secs,
        r.seeds,
        r.host
            .as_ref()
            .map_or_else(String::new, |h| format!(" Host: {h}.")),
        err_gap,
        calls_gap
    );
    for x in &r.rows {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            x.strategy,
            x.scenario,
            spread(&x.real_error_pct, 2),
            spread(&x.sim_error_pct, 2),
            spread(&x.real_calls_per_1k, 0),
            spread(&x.sim_calls_per_1k, 0),
            spread(&x.real_p99_us, 0),
            spread(&x.sim_p99_us, 0)
        );
    }
    md.push_str(
        "\nReal latency is measured at the load generator and includes the HTTP request to the \
         node and Docker networking; the simulator's is the decision wait alone (0 when a node \
         decides locally).\n\n",
    );
}

/// The real measurement of a row if there is one, else the simulated one.
fn best_side(r: &OverloadRow) -> (&Agg, &'static str) {
    r.real
        .as_ref()
        .map_or((&r.sim, "simulated"), |a| (a, "real"))
}

fn opt(a: Option<&Agg>, f: fn(&Agg) -> &Summary, d: usize) -> String {
    a.map_or("–".into(), |a| spread(f(a), d))
}

fn overload_section(md: &mut String, o: &OverloadResults) {
    let capacity = o.workers as u64 * 1_000 / o.service_ms.max(1);
    let _ = write!(
        md,
        "## Overload: static and adaptive concurrency limits\n\n\
         A backend with {} workers and a mean service time of {} ms (capacity {} requests/s) \
         sits behind a server that answers `504` after {} ms. The backend does not cancel late \
         work, so a queue that grows past the deadline turns into congestion collapse. Each \
         limit runs on the **same requests** (arrival and service times) {} seed(s) in the \
         simulator and {} seed(s) on the real `ConcurrencyLimitLayer` and backend (in-process \
         through the Axum router with real Tokio timers, no network), {} s per run.\n\n\
         - **none:** every request goes to the backend.\n\
         - **static:** a fixed limit of {}, the healthy worker count: the best static value when \
         it is known and never changes.\n\
         - **aimd:** +1 per success while the limit is in use, ×0.9 per timeout (threshold: \
         the deadline).\n\
         - **gradient2:** shrinks when recent latency rises above 1.5× its long-term average.\n\n\
         *Goodput* is answers `200` within the deadline, as a % of what could have succeeded: \
         per {} ms, the smaller of the offered requests and the capacity. Capacity uses the \
         mean service time, so a run can come out slightly above 100%. Latency is for the \
         `200`s.\n\n",
        o.workers,
        o.service_ms,
        capacity,
        o.deadline_ms,
        o.size.sim_seeds,
        o.size.real_seeds,
        o.size.run_secs,
        o.workers,
        o.bucket_ms
    );
    let mut gap: f64 = 0.0;
    for sc in &o.scenarios {
        let _ = write!(
            md,
            "### {}\n\n{}.\n\n![Goodput over time, {}](overload-{}.svg)\n\n\
             | Limit | Goodput real % | Goodput sim % | p99 real ms | p99 sim ms | Shed real % | Timed out real % |\n\
             |---|---:|---:|---:|---:|---:|---:|\n",
            sc.name,
            capitalise(&sc.description),
            sc.name,
            sc.name
        );
        for r in &sc.rows {
            let real = r.real.as_ref();
            if let Some(a) = real {
                gap = gap.max((a.goodput_pct.mean - r.sim.goodput_pct.mean).abs());
            }
            let _ = writeln!(
                md,
                "| {} | {} | {} | {} | {} | {} | {} |",
                r.limiter,
                opt(real, |a| &a.goodput_pct, 1),
                spread(&r.sim.goodput_pct, 1),
                opt(real, |a| &a.p99_ms, 0),
                spread(&r.sim.p99_ms, 0),
                opt(real, |a| &a.shed_pct, 1),
                opt(real, |a| &a.timeout_pct, 1)
            );
        }
        if let Some(best) = sc.rows.iter().max_by(|a, b| {
            best_side(a)
                .0
                .goodput_pct
                .mean
                .total_cmp(&best_side(b).0.goodput_pct.mean)
        }) {
            let (a, side) = best_side(best);
            let _ = writeln!(
                md,
                "\nHighest goodput ({side}): **{}**, {:.1}% of possible with p99 {:.0} ms.",
                best.limiter, a.goodput_pct.mean, a.p99_ms.mean
            );
        }
        // The trade-off: the fastest answers may come from a limit that serves fewer.
        if let Some(fast) = sc
            .rows
            .iter()
            .filter(|r| best_side(r).0.goodput_pct.n > 0 && best_side(r).0.timeout_pct.mean == 0.0)
            .min_by(|a, b| {
                best_side(a)
                    .0
                    .p99_ms
                    .mean
                    .total_cmp(&best_side(b).0.p99_ms.mean)
            })
        {
            let (a, side) = best_side(fast);
            let _ = writeln!(
                md,
                "Lowest p99 among limits with no timeouts ({side}): **{}**, {:.0} ms at {:.1}% of \
                 possible goodput.\n",
                fast.limiter, a.p99_ms.mean, a.goodput_pct.mean
            );
        } else {
            md.push('\n');
        }
    }
    if o.scenarios
        .iter()
        .any(|s| s.rows.iter().any(|r| r.real.is_some()))
    {
        let _ = writeln!(
            md,
            "Largest gap in goodput between the real layer and the simulator: **{gap:.1} \
             percentage points**.\n"
        );
    }
}

